import { useEffect, useRef } from 'react'
import { FlaskConical, X } from 'lucide-react'

/** Persistent notice shown above any Demo Mode content. Receives focus when it appears. */
export default function DemoBanner({
  description = 'This is pre-written example data. It was not generated by AI and is not based on your documents.',
  onExit,
}) {
  const bannerRef = useRef(null)
  useEffect(() => bannerRef.current?.focus(), [])

  return (
    <div
      ref={bannerRef}
      tabIndex={-1}
      role="note"
      aria-label="Demo Mode notice"
      className="flex flex-col gap-3 rounded-2xl border-2 border-dashed border-amber-300 bg-amber-50 p-4 outline-none sm:flex-row sm:items-center"
    >
      <span className="grid size-10 shrink-0 place-items-center rounded-xl bg-amber-100 text-amber-700">
        <FlaskConical className="size-5" aria-hidden="true" />
      </span>
      <div className="flex-1 text-sm text-amber-900">
        <p className="font-bold">Demo Mode: sample content</p>
        <p className="mt-0.5 leading-relaxed">{description}</p>
      </div>
      <button
        type="button"
        onClick={onExit}
        className="inline-flex shrink-0 items-center justify-center gap-2 rounded-xl bg-white px-4 py-2 text-sm font-semibold text-amber-900 ring-1 ring-amber-300 transition hover:bg-amber-100"
      >
        <X className="size-4" aria-hidden="true" />
        Exit demo
      </button>
    </div>
  )
}
