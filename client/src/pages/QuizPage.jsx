import { useState } from 'react'
import { ListChecks } from 'lucide-react'
import PageHeader from '../components/common/PageHeader'
import DemoBanner from '../components/generation/DemoBanner'
import DemoButton from '../components/generation/DemoButton'
import SourceBadge from '../components/generation/SourceBadge'
import QuizSession from '../components/quiz/QuizSession'
import QuizWorkspace from '../components/quiz/QuizWorkspace'
import StudyMaterialGate from '../components/study/StudyMaterialGate'
import { DEMO_QUIZ } from '../demo/quizDemo'
import { normalizeQuiz } from '../utils/quiz'

const demoQuestions = normalizeQuiz(DEMO_QUIZ).questions

export default function QuizPage() {
  const [isDemoOpen, setIsDemoOpen] = useState(false)

  function exitDemo() {
    setIsDemoOpen(false)
    requestAnimationFrame(() => document.querySelector('#main-content h1')?.focus())
  }

  return (
    <>
      <PageHeader
        eyebrow="Practice Quiz"
        title="Practice quizzes"
        description="Check your understanding with multiple-choice questions, instant feedback, and explanations."
      />
      {isDemoOpen ? (
        // Demo Mode: sample questions, clearly labeled; progress is not saved anywhere.
        <div className="space-y-6">
          <DemoBanner
            description="These quiz questions are pre-written example data. They were not generated by AI and are not based on your documents."
            onExit={exitDemo}
          />
          <div className="flex items-center gap-3">
            <SourceBadge origin="demo" />
            <span className="text-sm text-ink-500">{demoQuestions.length} sample questions</span>
          </div>
          <QuizSession questions={demoQuestions} />
        </div>
      ) : (
        <StudyMaterialGate
          icon={ListChecks}
          featureName="a practice quiz"
          emptyExtra={
            <div className="flex flex-col items-center gap-2 text-center text-sm text-ink-500">
              <p>Just want to see how it works?</p>
              <DemoButton onClick={() => setIsDemoOpen(true)} />
            </div>
          }
        >
          {(activeDocument) => (
            // key: a different document gets a fresh workspace, so nothing carries over.
            <QuizWorkspace key={activeDocument.id} document={activeDocument} onOpenDemo={() => setIsDemoOpen(true)} />
          )}
        </StudyMaterialGate>
      )}
    </>
  )
}
