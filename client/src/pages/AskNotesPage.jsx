import { useState } from 'react'
import { MessageCircleQuestionMark } from 'lucide-react'
import AskWorkspace from '../components/ask/AskWorkspace'
import ChatComposer from '../components/ask/ChatComposer'
import ChatLog from '../components/ask/ChatLog'
import PageHeader from '../components/common/PageHeader'
import DemoBanner from '../components/generation/DemoBanner'
import DemoButton from '../components/generation/DemoButton'
import StudyMaterialGate from '../components/study/StudyMaterialGate'
import { DEMO_CONVERSATION, DEMO_DOCUMENT_NAME } from '../demo/askDemo'

/** Demo Mode: a read-only sample conversation. Sending is disabled, so no API calls are made. */
function DemoConversation({ onExit }) {
  return (
    <div className="space-y-5">
      <DemoBanner
        description="This conversation is pre-written example data. It was not generated by AI and is not based on your documents."
        onExit={onExit}
      />
      <section aria-labelledby="demo-chat-title" className="overflow-clip rounded-3xl border border-cream-200 bg-white shadow-soft">
        <header className="border-b border-cream-200 px-4 py-3 sm:px-5">
          <h2 id="demo-chat-title" className="font-bold tracking-tight text-ink-900">
            Sample conversation
          </h2>
          <p className="text-xs text-ink-500">{DEMO_DOCUMENT_NAME}</p>
        </header>
        <ChatLog messages={DEMO_CONVERSATION} pending={null} documentText={null} />
        <ChatComposer
          value=""
          onChange={() => {}}
          onSend={() => {}}
          disabled
          placeholder="Sending is turned off in Demo Mode"
        />
      </section>
    </div>
  )
}

export default function AskNotesPage() {
  const [isDemoOpen, setIsDemoOpen] = useState(false)

  function exitDemo() {
    setIsDemoOpen(false)
    requestAnimationFrame(() => document.querySelector('#main-content h1')?.focus())
  }

  return (
    <>
      <PageHeader
        eyebrow="Ask My Notes"
        title="Ask my notes"
        description="Ask questions and get answers grounded in the material you've added. Sources are shown when the answer comes from your notes."
      />
      {isDemoOpen ? (
        <DemoConversation onExit={exitDemo} />
      ) : (
        <StudyMaterialGate
          icon={MessageCircleQuestionMark}
          featureName="questions about your notes"
          emptyExtra={
            <div className="flex flex-col items-center gap-2 text-center text-sm text-ink-500">
              <p>Just want to see how it works?</p>
              <DemoButton onClick={() => setIsDemoOpen(true)} />
            </div>
          }
        >
          {(activeDocument) => (
            // key: each document has its own conversation and in-flight request.
            <AskWorkspace key={activeDocument.id} document={activeDocument} onOpenDemo={() => setIsDemoOpen(true)} />
          )}
        </StudyMaterialGate>
      )}
    </>
  )
}
