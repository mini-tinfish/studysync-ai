import { useState } from 'react'
import { Layers } from 'lucide-react'
import PageHeader from '../components/common/PageHeader'
import FlashcardSession from '../components/flashcards/FlashcardSession'
import FlashcardsWorkspace from '../components/flashcards/FlashcardsWorkspace'
import DemoBanner from '../components/generation/DemoBanner'
import DemoButton from '../components/generation/DemoButton'
import SourceBadge from '../components/generation/SourceBadge'
import StudyMaterialGate from '../components/study/StudyMaterialGate'
import { DEMO_FLASHCARDS } from '../demo/flashcardsDemo'
import { normalizeFlashcards } from '../utils/flashcards'

const demoCards = normalizeFlashcards(DEMO_FLASHCARDS).cards

export default function FlashcardsPage() {
  const [isDemoOpen, setIsDemoOpen] = useState(false)

  function exitDemo() {
    setIsDemoOpen(false)
    requestAnimationFrame(() => document.querySelector('#main-content h1')?.focus())
  }

  return (
    <>
      <PageHeader
        eyebrow="Flashcards"
        title="Flashcards"
        description="Flip through question-and-answer cards and mark what you know."
      />
      {isDemoOpen ? (
        // Demo Mode: sample cards, clearly labeled; progress is not saved anywhere.
        <div className="space-y-6">
          <DemoBanner
            description="These flashcards are pre-written example data. They were not generated by AI and are not based on your documents."
            onExit={exitDemo}
          />
          <div className="flex items-center gap-3">
            <SourceBadge origin="demo" />
            <span className="text-sm text-ink-500">{demoCards.length} sample cards</span>
          </div>
          <FlashcardSession cards={demoCards} />
        </div>
      ) : (
        <StudyMaterialGate
          icon={Layers}
          featureName="flashcards"
          emptyExtra={
            <div className="flex flex-col items-center gap-2 text-center text-sm text-ink-500">
              <p>Just want to see how it works?</p>
              <DemoButton onClick={() => setIsDemoOpen(true)} />
            </div>
          }
        >
          {(activeDocument) => (
            // key: a different document gets a fresh workspace, so nothing carries over.
            <FlashcardsWorkspace
              key={activeDocument.id}
              document={activeDocument}
              onOpenDemo={() => setIsDemoOpen(true)}
            />
          )}
        </StudyMaterialGate>
      )}
    </>
  )
}
