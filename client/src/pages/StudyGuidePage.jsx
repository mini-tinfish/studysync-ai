import { useState } from 'react'
import { BookOpen } from 'lucide-react'
import PageHeader from '../components/common/PageHeader'
import DemoBanner from '../components/generation/DemoBanner'
import DemoButton from '../components/generation/DemoButton'
import SourceBadge from '../components/generation/SourceBadge'
import StudyGuideView from '../components/study-guide/StudyGuideView'
import StudyGuideWorkspace from '../components/study-guide/StudyGuideWorkspace'
import StudyMaterialGate from '../components/study/StudyMaterialGate'
import { DEMO_STUDY_GUIDE } from '../demo/studyGuideDemo'
import { normalizeStudyGuide } from '../utils/studyGuide'

const demoGuide = normalizeStudyGuide(DEMO_STUDY_GUIDE)

export default function StudyGuidePage() {
  const [isDemoOpen, setIsDemoOpen] = useState(false)

  function exitDemo() {
    setIsDemoOpen(false)
    requestAnimationFrame(() => document.querySelector('#main-content h1')?.focus())
  }

  return (
    <>
      <PageHeader
        eyebrow="Study Guide"
        title="Study guides"
        description="Organized summaries of the key ideas, terms, and takeaways in your materials."
      />
      {isDemoOpen ? (
        // Demo Mode: hand-written sample content, visibly labeled and kept apart from real results.
        <div className="space-y-5">
          <DemoBanner
            description="This study guide is pre-written example data. It was not generated by AI and is not based on your documents."
            onExit={exitDemo}
          />
          <StudyGuideView guide={demoGuide} idPrefix="demo-guide" badge={<SourceBadge origin="demo" />} />
        </div>
      ) : (
        <StudyMaterialGate
          icon={BookOpen}
          featureName="a study guide"
          emptyExtra={
            <div className="flex flex-col items-center gap-2 text-center text-sm text-ink-500">
              <p>Just want to see how it works?</p>
              <DemoButton onClick={() => setIsDemoOpen(true)} />
            </div>
          }
        >
          {(activeDocument) => (
            // key: a different document gets a fresh workspace, so nothing carries over.
            <StudyGuideWorkspace
              key={activeDocument.id}
              document={activeDocument}
              onOpenDemo={() => setIsDemoOpen(true)}
            />
          )}
        </StudyMaterialGate>
      )}
    </>
  )
}
